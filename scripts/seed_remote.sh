_jn() {
  local expr="$1" json="$2" def="${3:-}"
  local result
  result=$(printf '%s' "$json" | node -e "
const s=require('fs').readFileSync(0,'utf8');
try{const d=JSON.parse(s);const r=eval(process.argv[1]);if(r!=null&&r!==undefined)process.stdout.write(String(r));}
