" -- "$expr" 2>/dev/null)
  echo "${result:-$def}"
}

tmpjson() { printf '%s' "$1" > "/tmp/stocki_seed_$$.json"; echo "/tmp/stocki_seed_$$.json"; }

imp() {
  # imp KEY FILE_PATH "label"
  local key="$1" file="$2" label="$3"
  local res
  res=$(curl -s -b "$CK" -X POST "$BASE/api/import/opening" \
    -H "Content-Type: application/json" \
    --data-binary @"$file")
  if [[ "$res" == *'"already_imported"'* ]]; then
    skip "$label"
  elif [[ "$res" == *'"ok":true'* ]]; then
    done_ "$label"
  else
    echo "  ❌  $label — $res"
  fi
}

rcv() {
  # rcv KEY WH_ID LINES_JSON "label"
  local key="$1" wh="$2" lines="$3" label="$4"
  local res
  res=$(curl -s -b "$CK" -X POST "$BASE/api/documents/receive" \
    -H "Content-Type: application/json" \
    -d "{\"idempotency_key\":\"${key}\",\"warehouse_id\":${wh},\"doc_date\":\"2026-10-01\",\"lines\":${lines}}")
  if [[ "$res" == *'"idempotent":true'* ]]; then
    skip "$label"
  elif [[ "$res" == *'"doc_no"'* ]]; then
    done_ "$label"
  else
    echo "  ❌  $label — ${res:0:120}"
  fi
}

iss() {
  # iss KEY WH_ID LINES_JSON "label"
  local key="$1" wh="$2" lines="$3" label="$4"
  local res
  res=$(curl -s -b "$CK" -X POST "$BASE/api/documents/issue" \
    -H "Content-Type: application/json" \
    -d "{\"idempotency_key\":\"${key}\",\"warehouse_id\":${wh},\"doc_date\":\"2026-10-15\",\"lines\":${lines}}")
  if [[ "$res" == *'"idempotent":true'* ]]; then
    skip "$label"
  elif [[ "$res" == *'"doc_no"'* ]]; then
    done_ "$label"
  else
    echo "  ❌  $label — ${res:0:120}"
  fi
}

