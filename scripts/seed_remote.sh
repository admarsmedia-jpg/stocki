done_() { echo "  ✅  $*"; SEEDED=$((SEEDED+1)); }
skip() { echo "  ⏭  $* (already seeded)"; SKIPPED=$((SKIPPED+1)); }

cleanup() { rm -f "$CK" /tmp/stocki_seed_*.json 2>/dev/null || true; }
